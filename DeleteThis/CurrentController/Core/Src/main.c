char* substring(char *s, int a, int b) {
	char *t = malloc(sizeof(char) * ((b - a) + 1));
	for (int z = 0; z < (b - a) + 1; z++) {
		t[z] = 0x00;
	}
	strncpy(t, s + a, b - a);
	return t;
}
int indexOf(char *source, char *key, int startIndex) {
	char *found = strstr((source + startIndex), key);
	if (found != NULL) {
		int index = found - source;
		return index;
	}
	return -1;
}
void parseDataIfValid(char *data) {
	if (indexOf(data, "{", 0) == 0 && indexOf(data, "}", 0) != -1) {
		char * val = substring(data, 1, indexOf(data, "}", 0));
		targetCurrentma = atoi(val);
		lastReceivedms = HAL_GetTick();
		free(val);
	}
}
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	if (received == NULL) {
		received = malloc(sizeof(char) * 2);
		received[0] = 0x00;
		received[1] = 0x00;
	} else {
		received = realloc(received, sizeof(char) * (strlen(received) + 2));
	}

	strcat(received, dataRx);
	if (dataRx[0] == '\n') {
		parseDataIfValid(received);
		free(received);
		received = NULL;
	} else if (strlen(received) > 100) { //100 is mx length of receiveddata per value
		free(received);
		received = NULL;
	}
	HAL_UART_Receive_IT(&huart1, dataRx, 1);

}
